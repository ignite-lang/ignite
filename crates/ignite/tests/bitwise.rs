//! The bitwise operators of `docs/slice.md` 27 across the evaluator and
//! both targets: a program generated from random operands (a fixed seed,
//! `IGNITE_BITWISE_SEED` to change it) applies every operator to every
//! pair, and the evaluator, a Rust-target build and an LLVM-target build
//! must each print the values Rust's `i64` gives under 27.2's shift rule.
//! `fixtures/bitwise/codecs.ignite` holds SHA-1 and base64 written with
//! the operators: its inline tests are the vectors of RFC 3174 and
//! RFC 4648 on both targets, and the ignored
//! `codecs_within_3x_of_hand_written_rust` times it against
//! `fixtures/bitwise/codecs.rs` on a 1 MiB input (27.5).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, Instant};

use ignite::Target;
use ignite_eval::{Evaluator, Fuel};
use ignite_types::QualName;

use crate::common;

/// Operands per operator besides the edge cases.
const RANDOM_PAIRS: usize = 48;

/// The operators of 27.1 with the name of the generated fn that applies it.
const BINARY: [(&str, &str); 5] = [
    ("and_all", "&"),
    ("or_all", "|"),
    ("xor_all", "^"),
    ("shl_all", "<<"),
    ("shr_all", ">>"),
];

/// xorshift64*: deterministic operands from a seed.
struct Operands(u64);

impl Operands {
    fn next(&mut self) -> i64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_f491_4f6c_dd1d) as i64
    }
}

/// 27.2: `a << n` is `a` shifted left by `n` for `n` in `0..64`, bits
/// shifted out dropped, and 0 for any other `n`.
fn shl(a: i64, n: i64) -> i64 {
    if (0..64).contains(&n) { a << n } else { 0 }
}

/// 27.2: `a >> n` shifts arithmetically for `n` in `0..64` and gives the
/// sign fill (0 or -1) for any other `n`.
fn shr(a: i64, n: i64) -> i64 {
    if (0..64).contains(&n) {
        a >> n
    } else if a < 0 {
        -1
    } else {
        0
    }
}

fn apply(op: &str, a: i64, b: i64) -> i64 {
    match op {
        "&" => a & b,
        "|" => a | b,
        "^" => a ^ b,
        "<<" => shl(a, b),
        ">>" => shr(a, b),
        _ => unreachable!("{op}"),
    }
}

/// An `Int` literal of the generated program.
fn literal(n: i64) -> String {
    n.to_string()
}

fn list(values: &[i64]) -> String {
    let items: Vec<String> = values.iter().map(|v| literal(*v)).collect();
    format!("[{}]", items.join(", "))
}

/// The operand pairs of `op`: edge cases, then random ones. Shift amounts
/// are mostly in `0..64`, plus the negative and too-large amounts 27.2
/// defines.
fn pairs(op: &str, rng: &mut Operands) -> Vec<(i64, i64)> {
    let edges = [0, 1, -1, i64::MIN, i64::MAX, 0x5555_5555_5555_5555];
    let shift = op == "<<" || op == ">>";
    let amounts = [0, 1, 31, 32, 63, 64, 65, 100, -1, -64, i64::MIN, i64::MAX];
    let mut out = Vec::new();
    for a in edges {
        if shift {
            for n in amounts {
                out.push((a, n));
            }
        } else {
            for b in edges {
                out.push((a, b));
            }
        }
    }
    for _ in 0..RANDOM_PAIRS {
        let a = rng.next();
        let b = rng.next();
        let b = if shift {
            match b.rem_euclid(8) {
                0 => b,
                1 => 64 + b.rem_euclid(200),
                2 => -(b.rem_euclid(200)) - 1,
                _ => b.rem_euclid(64),
            }
        } else {
            b
        };
        out.push((a, b));
    }
    out
}

/// The generated program and, per printed fn in declaration order, the
/// debug text Rust's `i64` gives.
fn program(seed: u64) -> (String, Vec<(String, String)>) {
    let mut rng = Operands(seed | 1);
    let mut source = String::from("package bitwise_differential\n\n");
    source.push_str(
        "// Generated by crates/ignite/tests/bitwise.rs: every operator of\n\
         // docs/slice.md 27 over operand lists, read at run time.\n\n",
    );
    let mut expected = Vec::new();
    let mut fns = String::new();
    for (name, op) in BINARY {
        let pairs = pairs(op, &mut rng);
        let lefts: Vec<i64> = pairs.iter().map(|p| p.0).collect();
        let rights: Vec<i64> = pairs.iter().map(|p| p.1).collect();
        let results: Vec<i64> = pairs.iter().map(|&(a, b)| apply(op, a, b)).collect();
        writeln!(
            fns,
            "fn {name}() -> List<Int> {{\n  let lefts = {}\n  let rights = {}\n  \
             var out: List<Int> = []\n  var i = 0\n  while i < lefts.len() {{\n    \
             out.push(lefts[i] {op} rights[i])\n    i = i + 1\n  }}\n  out\n}}\n",
            list(&lefts),
            list(&rights)
        )
        .unwrap();
        expected.push((name.to_string(), list(&results)));
    }
    let mut operands: Vec<i64> = vec![0, 1, -1, i64::MIN, i64::MAX];
    operands.extend((0..RANDOM_PAIRS).map(|_| rng.next()));
    let nots: Vec<i64> = operands.iter().map(|a| !a).collect();
    writeln!(
        fns,
        "fn not_all() -> List<Int> {{\n  var out: List<Int> = []\n  \
         for a in {} {{\n    out.push(~a)\n  }}\n  out\n}}\n",
        list(&operands)
    )
    .unwrap();
    expected.push(("not_all".to_string(), list(&nots)));
    // Precedence, evaluated: `|` looser than `^` looser than `&` looser
    // than the shifts looser than `+`; the comparison looser than all.
    let (a, b, c) = (rng.next() >> 8, rng.next() >> 8, rng.next() >> 8);
    writeln!(
        fns,
        "fn mixed() -> List<Int> {{\n  let a = {a}\n  let b = {b}\n  let c = {c}\n  \
         let d = if a & b == b & a {{ 1 }} else {{ 0 }}\n  \
         [a | b ^ c & a << 3 + 1, ~a & b | c >> 2 ^ a, d]\n}}\n"
    )
    .unwrap();
    let mixed = [a | (b ^ (c & shl(a, 3 + 1))), ((!a) & b) | (shr(c, 2) ^ a), 1];
    expected.push(("mixed".to_string(), list(&mixed)));
    source.push_str(&fns);
    source.push_str(
        "fn show(text: Text) -> Result<Unit, IoError> requires [stdout.write] {\n  \
         var bytes = text.to_bytes()\n  bytes.push(10)\n  return Stdout.write_all(bytes)\n}\n\n\
         type Printer {\n  executable: Text\n}\n\n\
         fn Printer.main(self: Printer) -> Result<Unit, IoError> {\n",
    );
    for (name, _) in &expected {
        writeln!(source, "  show({name}().debug())?").unwrap();
    }
    source.push_str(
        "  Ok(Unit)\n}\n\nsystem Bits {\n  component bitprint: Printer { executable = \"bitprint\" }\n}\n",
    );
    (source, expected)
}

fn seed() -> u64 {
    std::env::var("IGNITE_BITWISE_SEED")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(0x1971_0bad_5eed)
}

fn build(file: &Path, target: Target, out: PathBuf, release: bool) -> Vec<PathBuf> {
    let options = ignite::BuildOptions {
        target,
        out: Some(out),
        release,
        runtime: (target == Target::Llvm).then(common::runtime_archive),
        ..Default::default()
    };
    ignite::build(file, &options)
        .unwrap_or_else(|e| panic!("{target:?}: {e}"))
        .executables
}

fn run_lines(exe: &Path) -> Vec<String> {
    let output = Command::new(exe)
        .output()
        .unwrap_or_else(|e| panic!("run {}: {e}", exe.display()));
    assert!(
        output.status.success(),
        "{}: {}\n{}",
        exe.display(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout)
        .expect("UTF-8")
        .lines()
        .map(str::to_string)
        .collect()
}

/// 27.4: the evaluator and both targets print what Rust's `i64` gives,
/// fn by fn.
#[test]
fn operators_agree_across_the_evaluator_and_both_targets() {
    let seed = seed();
    let (source, expected) = program(seed);
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("bitwise");
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("differential.ignite");
    std::fs::write(&file, &source).unwrap();

    let loaded = ignite::load(&file, None).unwrap_or_else(|e| panic!("seed {seed}: {e}"));
    let modules = loaded.modules();
    let mut evaluator = Evaluator::new(&modules, Fuel::default());
    let module = loaded.types().module.clone();
    for (name, want) in &expected {
        let got = evaluator
            .call(&QualName::new(module.clone(), name.clone()), Vec::new())
            .unwrap_or_else(|e| panic!("seed {seed}, evaluator {name}: {e:?}"))
            .debug_text();
        assert_eq!(&got, want, "seed {seed}, evaluator {name}");
    }

    std::thread::scope(|scope| {
        let handles: Vec<_> = [Target::Rust, Target::Llvm]
            .into_iter()
            .map(|target| {
                let (file, dir) = (&file, &dir);
                scope.spawn(move || {
                    let out = dir.join(format!("out-{target:?}").to_lowercase());
                    let exes = build(file, target, out, false);
                    let exe = exes
                        .iter()
                        .find(|p| p.file_stem().and_then(|s| s.to_str()) == Some("bitprint"))
                        .unwrap_or_else(|| panic!("no bitprint in {exes:?}"))
                        .clone();
                    (target, run_lines(&exe))
                })
            })
            .collect();
        for handle in handles {
            let (target, lines) = handle.join().expect("target thread");
            assert_eq!(lines.len(), expected.len(), "seed {seed}, {target:?}");
            for ((name, want), got) in expected.iter().zip(&lines) {
                assert_eq!(got, want, "seed {seed}, {target:?} {name}");
            }
        }
    });
}

fn codecs() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/bitwise/codecs.ignite")
}

/// 27.5: the RFC 3174 and RFC 4648 vectors pass on both targets.
#[test]
fn sha1_and_base64_vectors_on_both_targets() {
    let out = Path::new(env!("CARGO_TARGET_TMPDIR")).join("bitwise-codecs");
    std::thread::scope(|scope| {
        let handles: Vec<_> = ["rust", "llvm"]
            .into_iter()
            .map(|target| {
                let out = &out;
                scope.spawn(move || {
                    let mut command = Command::new(env!("CARGO_BIN_EXE_ignite"));
                    command
                        .arg("test")
                        .arg(codecs())
                        .args(["--target", target, "--out"])
                        .arg(out.join(target))
                        .arg("--runtime")
                        .arg(common::runner_archive());
                    if target == "rust" {
                        command.arg("--target-dir").arg(out.join("cargo"));
                    }
                    let output = command.output().expect("run ignite test");
                    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
                    assert_eq!(
                        output.status.code(),
                        Some(0),
                        "{target}: {stdout}\n{}",
                        String::from_utf8_lossy(&output.stderr)
                    );
                    assert!(
                        stdout.contains("test result: ok. 4 passed; 0 failed"),
                        "{target}: {stdout}"
                    );
                })
            })
            .collect();
        for handle in handles {
            handle.join().expect("target thread");
        }
    });
}

/// The median wall time of `runs` runs of `exe`, and its output.
fn timed(exe: &Path, runs: usize) -> (Duration, String) {
    let mut times = Vec::new();
    let mut last = String::new();
    for _ in 0..runs {
        let start = Instant::now();
        let output = Command::new(exe).output().expect("run");
        times.push(start.elapsed());
        assert!(output.status.success(), "{}", exe.display());
        last = String::from_utf8_lossy(&output.stdout).into_owned();
    }
    times.sort();
    (times[runs / 2], last)
}

/// 27.5: the codecs' executable (SHA-1 and base64 of 1 MiB, 8 rounds) on
/// each target, built `--release`, against `fixtures/bitwise/codecs.rs`
/// built with `rustc -O`; each within 3x. Ignored: it times release
/// builds; `cargo test -p ignite --test main bitwise:: -- --ignored
/// --nocapture` prints the record.
#[test]
#[ignore]
fn codecs_within_3x_of_hand_written_rust() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("bitwise-bench");
    std::fs::create_dir_all(&dir).unwrap();
    let reference = dir.join("codecs-rs");
    let status = Command::new("rustc")
        .args(["-O", "--edition", "2024", "-o"])
        .arg(&reference)
        .arg(Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/bitwise/codecs.rs"))
        .status()
        .expect("run rustc");
    assert!(status.success(), "rustc");
    let (rust_time, rust_out) = timed(&reference, 5);
    println!("hand-written Rust: {rust_time:?}");
    for target in [Target::Rust, Target::Llvm] {
        let out = dir.join(format!("out-{target:?}").to_lowercase());
        let exes = build(&codecs(), target, out, true);
        let exe = exes
            .iter()
            .find(|p| p.file_stem().and_then(|s| s.to_str()) == Some("codecs"))
            .unwrap_or_else(|| panic!("no codecs in {exes:?}"))
            .clone();
        let (time, printed) = timed(&exe, 5);
        assert_eq!(printed, rust_out, "{target:?} prints what the reference prints");
        let ratio = time.as_secs_f64() / rust_time.as_secs_f64();
        println!("{target:?}: {time:?}, ratio {ratio:.2}");
        assert!(ratio <= 3.0, "{target:?}: {ratio:.2} times the hand-written Rust");
    }
}
