/// Operands per operator besides the edge cases.
const RANDOM_PAIRS: usize = 48;

/// The operators of 29.1 with the name of the generated fn that applies it.
const BINARY: [(&str, &str); 5] = [
    ("and_all", "&"),
    ("or_all", "|"),
    ("xor_all", "^"),
    ("shl_all", "<<"),
    ("shr_all", ">>"),
];

/// xorshift64*: deterministic operands from a seed.
struct Operands(u64);

impl Operands {
    fn next(&mut self) -> i64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_f491_4f6c_dd1d) as i64
    }
}

/// 29.2: `a << n` is `a` shifted left by `n` for `n` in `0..64`, bits
/// shifted out dropped, and 0 for any other `n`.
fn shl(a: i64, n: i64) -> i64 {
    if (0..64).contains(&n) { a << n } else { 0 }
}

/// 29.2: `a >> n` shifts arithmetically for `n` in `0..64` and gives the
/// sign fill (0 or -1) for any other `n`.
fn shr(a: i64, n: i64) -> i64 {
    if (0..64).contains(&n) {
        a >> n
    } else if a < 0 {
        -1
    } else {
        0
    }
}

fn apply(op: &str, a: i64, b: i64) -> i64 {
    match op {
        "&" => a & b,
        "|" => a | b,
        "^" => a ^ b,
        "<<" => shl(a, b),
        ">>" => shr(a, b),
        _ => unreachable!("{op}"),
    }
}

/// An `Int` literal of the generated program; `i64::MIN` as the
/// expression `MAX - ... - 1`, as `fixtures/tests/checked.ignite` writes it.
fn literal(n: i64) -> String {
    if n == i64::MIN {
        "-9223372036854775807 - 1".to_string()
    } else {
        n.to_string()
    }
}

/// The debug text of a `List<Int>`.
fn shown(values: &[i64]) -> String {
    let items: Vec<String> = values.iter().map(i64::to_string).collect();
    format!("[{}]", items.join(", "))
}

/// A `List<Int>` literal of the generated program.
fn list(values: &[i64]) -> String {
    let items: Vec<String> = values.iter().map(|v| literal(*v)).collect();
    format!("[{}]", items.join(", "))
}

/// The operand pairs of `op`: edge cases, then random ones. Shift amounts
/// are mostly in `0..64`, plus the negative and too-large amounts 29.2
/// defines.
fn pairs(op: &str, rng: &mut Operands) -> Vec<(i64, i64)> {
    let edges = [0, 1, -1, i64::MIN, i64::MAX, 0x5555_5555_5555_5555];
    let shift = op == "<<" || op == ">>";
    let amounts = [0, 1, 31, 32, 63, 64, 65, 100, -1, -64, i64::MIN, i64::MAX];
    let mut out = Vec::new();
    for a in edges {
        if shift {
            for n in amounts {
                out.push((a, n));
            }
        } else {
            for b in edges {
                out.push((a, b));
            }
        }
    }
    for _ in 0..RANDOM_PAIRS {
        let a = rng.next();
        let b = rng.next();
        let b = if shift {
            match b.rem_euclid(8) {
                0 => b,
                1 => 64 + b.rem_euclid(200),
                2 => -(b.rem_euclid(200)) - 1,
                _ => b.rem_euclid(64),
            }
        } else {
            b
        };
        out.push((a, b));
    }
    out
}

/// The generated program and, per printed fn in declaration order, the
/// debug text Rust's `i64` gives.
fn program(seed: u64) -> (String, Vec<(String, String)>) {
    let mut rng = Operands(seed | 1);
    let mut source = String::from("package bitwise_differential\n\n");
    source.push_str(
        "// Generated by crates/ignite/tests/bitwise.rs: every operator of\n\
         // docs/slice.md 29 over operand lists, read at run time.\n\n",
    );
    let mut expected = Vec::new();
    let mut fns = String::new();
    for (name, op) in BINARY {
        let pairs = pairs(op, &mut rng);
        let lefts: Vec<i64> = pairs.iter().map(|p| p.0).collect();
        let rights: Vec<i64> = pairs.iter().map(|p| p.1).collect();
        let results: Vec<i64> = pairs.iter().map(|&(a, b)| apply(op, a, b)).collect();
        writeln!(
            fns,
            "fn {name}() -> List<Int> {{\n  let lefts = {}\n  let rights = {}\n  \
             var out: List<Int> = []\n  var i = 0\n  while i < lefts.len() {{\n    \
             out.push(lefts[i] {op} rights[i])\n    i = i + 1\n  }}\n  out\n}}\n",
            list(&lefts),
            list(&rights)
        )
        .unwrap();
        expected.push((name.to_string(), shown(&results)));
    }
    let mut operands: Vec<i64> = vec![0, 1, -1, i64::MIN, i64::MAX];
    operands.extend((0..RANDOM_PAIRS).map(|_| rng.next()));
    let nots: Vec<i64> = operands.iter().map(|a| !a).collect();
    writeln!(
        fns,
        "fn not_all() -> List<Int> {{\n  var out: List<Int> = []\n  \
         for a in {} {{\n    out.push(~a)\n  }}\n  out\n}}\n",
        list(&operands)
    )
    .unwrap();
    expected.push(("not_all".to_string(), shown(&nots)));
    // Precedence, evaluated: `|` looser than `^` looser than `&` looser
    // than the shifts looser than `+`; the comparison looser than all.
    let (a, b, c) = (rng.next() >> 8, rng.next() >> 8, rng.next() >> 8);
    writeln!(
        fns,
        "fn mixed() -> List<Int> {{\n  let a = {a}\n  let b = {b}\n  let c = {c}\n  \
         let d = if a & b == b & a {{ 1 }} else {{ 0 }}\n  \
         [a | b ^ c & a << 3 + 1, ~a & b | c >> 2 ^ a, d]\n}}\n"
    )
    .unwrap();
    let mixed = [
        a | (b ^ (c & shl(a, 3 + 1))),
        ((!a) & b) | (shr(c, 2) ^ a),
        1,
    ];
    expected.push(("mixed".to_string(), shown(&mixed)));
    source.push_str(&fns);
    source.push_str(
        "fn show(text: Text) -> Result<Unit, IoError> requires [stdout.write] {\n  \
         var bytes = text.to_bytes()\n  bytes.push(10)\n  return Stdout.write_all(bytes)\n}\n\n\
         type Printer {\n  executable: Text\n}\n\n\
         fn Printer.main(self: Printer) -> Result<Unit, IoError> {\n",
    );
    for (name, _) in &expected {
        writeln!(source, "  show({name}().debug())?").unwrap();
    }
    source.push_str(
        "  Ok(Unit)\n}\n\nsystem Bits {\n  component bitprint: Printer { executable = \"bitprint\" }\n}\n",
    );
    (source, expected)
}

fn seed() -> u64 {
    std::env::var("IGNITE_BITWISE_SEED")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(0x1971_0bad_5eed)
}

/// `ignite build` of `file`; an LLVM build links `runtime`, by default
/// this test binary's (debug) runtime.
fn build(
    file: &Path,
    target: Target,
    out: PathBuf,
    release: bool,
    runtime: Option<PathBuf>,
) -> Vec<PathBuf> {
    let options = ignite::BuildOptions {
        target,
        out: Some(out),
        release,
        runtime: (target == Target::Llvm).then(|| runtime.unwrap_or_else(common::runtime_archive)),
        ..Default::default()
    };
    ignite::build(file, &options)
        .unwrap_or_else(|e| panic!("{target:?}: {e}"))
        .executables
}

fn run_lines(exe: &Path) -> Vec<String> {
    let output = Command::new(exe)
        .output()
        .unwrap_or_else(|e| panic!("run {}: {e}", exe.display()));
    assert!(
        output.status.success(),
        "{}: {}\n{}",
        exe.display(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout)
        .expect("UTF-8")
        .lines()
        .map(str::to_string)
        .collect()
}

/// 29.4: the evaluator and both targets print what Rust's `i64` gives,
/// fn by fn.
#[test]
fn operators_agree_across_the_evaluator_and_both_targets() {
    let seed = seed();
    let (source, expected) = program(seed);
    agree("bitwise", "bitprint", seed, &source, &expected);
}

/// The `U32` edges of `docs/fixed-width-ints.md` row 4 and one more.
const WORD_EDGES: [u32; 5] = [0, 1, 1 << 31, u32::MAX, 0x5555_5555];

/// Shift and rotate amounts: row 4's and the far ones.
const WORD_AMOUNTS: [i64; 10] = [-1, 0, 31, 32, 33, 1, 7, 64, i64::MIN, i64::MAX];

/// One generated fn: its name, the Ignite operator or expression, and Rust's answer.
type Case<F> = (&'static str, &'static str, F);
type WordCase = Case<fn(u32, u32) -> u32>;
type CompareCase = Case<fn(&u32, &u32) -> bool>;
type ShiftCase = Case<fn(u32, i64) -> u32>;

/// 32.1: a shift by an amount outside `0..32` gives 0; `>>` is logical.
fn word_shift(op: &str, a: u32, n: i64) -> u32 {
    match u32::try_from(n).ok().filter(|n| *n < 32) {
        Some(n) if op == "<<" => a << n,
        Some(n) => a >> n,
        None => 0,
    }
}

/// The debug text of values printed as decimals.
fn shown_words<T: ToString>(values: &[T]) -> String {
    let items: Vec<String> = values.iter().map(T::to_string).collect();
    format!("[{}]", items.join(", "))
}

fn word_list(values: &[u32]) -> String {
    shown_words(values)
}

/// The `U32` program: every operator, rotate and conversion of 32.1 to
/// 32.3 over edge and random operands read from lists at run time, and
/// per fn the debug text Rust's `u32` gives.
fn word_program(seed: u64) -> (String, Vec<(String, String)>) {
    let mut rng = Operands(seed | 1);
    let random = |rng: &mut Operands, count: usize| -> Vec<u32> {
        (0..count).map(|_| rng.next() as u32).collect()
    };
    let mut pairs: Vec<(u32, u32)> = Vec::new();
    for a in WORD_EDGES {
        for b in WORD_EDGES {
            pairs.push((a, b));
        }
    }
    let extra = random(&mut rng, 2 * RANDOM_PAIRS);
    pairs.extend(extra.chunks(2).map(|p| (p[0], p[1])));
    let lefts: Vec<u32> = pairs.iter().map(|p| p.0).collect();
    let rights: Vec<u32> = pairs.iter().map(|p| p.1).collect();
    let nonzero: Vec<(u32, u32)> = pairs.iter().copied().filter(|p| p.1 != 0).collect();
    let mut operands: Vec<u32> = WORD_EDGES.to_vec();
    operands.extend(random(&mut rng, RANDOM_PAIRS));
    let mut amounts: Vec<(u32, i64)> = Vec::new();
    for a in operands.iter().take(WORD_EDGES.len() + 8) {
        for n in WORD_AMOUNTS {
            amounts.push((*a, n));
        }
    }
    let mut source = String::from("package bitwise_words\n\n");
    source.push_str(
        "// Generated by crates/ignite/tests/bitwise.rs: every U32 operator,\n\
         // rotate and conversion of docs/slice.md 32 over operand lists.\n\n",
    );
    let mut expected: Vec<(String, String)> = Vec::new();
    let binary = |name: &str, op: &str, result: &str, pairs: &[(u32, u32)]| {
        let lefts: Vec<u32> = pairs.iter().map(|p| p.0).collect();
        let rights: Vec<u32> = pairs.iter().map(|p| p.1).collect();
        format!(
            "fn {name}() -> List<{result}> {{\n  let lefts: List<U32> = {}\n  let rights: List<U32> = {}\n  \
             var out: List<{result}> = []\n  var i = 0\n  while i < lefts.len() {{\n    \
             out.push(lefts[i] {op} rights[i])\n    i = i + 1\n  }}\n  out\n}}\n\n",
            word_list(&lefts),
            word_list(&rights)
        )
    };
    let words: [WordCase; 6] = [
        ("add_all", "+", u32::wrapping_add),
        ("sub_all", "-", u32::wrapping_sub),
        ("mul_all", "*", u32::wrapping_mul),
        ("and_all", "&", |a, b| a & b),
        ("or_all", "|", |a, b| a | b),
        ("xor_all", "^", |a, b| a ^ b),
    ];
    for (name, op, f) in words {
        source.push_str(&binary(name, op, "U32", &pairs));
        let results: Vec<u32> = pairs.iter().map(|&(a, b)| f(a, b)).collect();
        expected.push((name.to_string(), shown_words(&results)));
    }
    for (name, op, f) in [
        ("div_all", "/", (|a, b| a / b) as fn(u32, u32) -> u32),
        ("rem_all", "%", |a, b| a % b),
    ] {
        source.push_str(&binary(name, op, "U32", &nonzero));
        let results: Vec<u32> = nonzero.iter().map(|&(a, b)| f(a, b)).collect();
        expected.push((name.to_string(), shown_words(&results)));
    }
    let comparisons: [CompareCase; 6] = [
        ("eq_all", "==", u32::eq),
        ("ne_all", "!=", u32::ne),
        ("lt_all", "<", u32::lt),
        ("le_all", "<=", u32::le),
        ("gt_all", ">", u32::gt),
        ("ge_all", ">=", u32::ge),
    ];
    for (name, op, f) in comparisons {
        source.push_str(&binary(name, op, "Bool", &pairs));
        let results: Vec<bool> = lefts.iter().zip(&rights).map(|(a, b)| f(a, b)).collect();
        expected.push((name.to_string(), shown_words(&results)));
    }
    let by_amount = |name: &str, apply: &str, amounts: &[(u32, i64)]| {
        let words: Vec<u32> = amounts.iter().map(|p| p.0).collect();
        let ns: Vec<String> = amounts.iter().map(|p| literal(p.1)).collect();
        format!(
            "fn {name}() -> List<U32> {{\n  let words: List<U32> = {}\n  let amounts = [{}]\n  \
             var out: List<U32> = []\n  var i = 0\n  while i < words.len() {{\n    \
             out.push({apply})\n    i = i + 1\n  }}\n  out\n}}\n\n",
            word_list(&words),
            ns.join(", ")
        )
    };
    let shifts: [ShiftCase; 4] = [
        ("shl_all", "words[i] << amounts[i]", |a, n| {
            word_shift("<<", a, n)
        }),
        ("shr_all", "words[i] >> amounts[i]", |a, n| {
            word_shift(">>", a, n)
        }),
        ("rotl_all", "words[i].rotate_left(amounts[i])", |a, n| {
            a.rotate_left((n & 31) as u32)
        }),
        ("rotr_all", "words[i].rotate_right(amounts[i])", |a, n| {
            a.rotate_right((n & 31) as u32)
        }),
    ];
    for (name, apply, f) in shifts {
        source.push_str(&by_amount(name, apply, &amounts));
        let results: Vec<u32> = amounts.iter().map(|&(a, n)| f(a, n)).collect();
        expected.push((name.to_string(), shown_words(&results)));
    }
    // A shift by a literal amount, which both backends emit directly.
    let constant: Vec<u32> = operands
        .iter()
        .map(|a| (a << 7) ^ (a >> 25) ^ (a << 31) ^ a)
        .collect();
    let unary: [(&str, &str, &str, Vec<String>); 8] = [
        (
            "neg_all",
            "U32",
            "-a",
            operands
                .iter()
                .map(|a| a.wrapping_neg().to_string())
                .collect(),
        ),
        (
            "not_all",
            "U32",
            "~a",
            operands.iter().map(|a| (!a).to_string()).collect(),
        ),
        (
            "const_shift_all",
            "U32",
            "a << 7 ^ a >> 25 ^ a << 31 ^ a >> 0",
            constant.iter().map(u32::to_string).collect(),
        ),
        (
            "to_int_all",
            "Int",
            "a.to_int()",
            operands.iter().map(|a| a.to_string()).collect(),
        ),
        (
            "to_byte_all",
            "Int",
            "match a.to_byte() {\n      Some(b) => b.to_int()\n      None => -1\n    }",
            operands
                .iter()
                .map(|a| u8::try_from(*a).map_or(-1, i64::from).to_string())
                .collect(),
        ),
        (
            "wrap_byte_all",
            "Byte",
            "a.wrap_byte()",
            operands.iter().map(|a| (*a as u8).to_string()).collect(),
        ),
        (
            "to_text_all",
            "Text",
            "a.to_text()",
            operands.iter().map(|a| format!("\"{a}\"")).collect(),
        ),
        (
            "classify_all",
            "Int",
            "match a {\n      0 => 0\n      1..=255 => 1\n      2147483648 => 2\n      256..=4294967294 => 3\n      _ => 4\n    }",
            operands
                .iter()
                .map(|a| match a {
                    0 => 0,
                    1..=255 => 1,
                    2147483648 => 2,
                    256..=4294967294 => 3,
                    _ => 4,
                })
                .map(|n: i64| n.to_string())
                .collect(),
        ),
    ];
    for (name, result, apply, values) in unary {
        writeln!(
            source,
            "fn {name}() -> List<{result}> {{\n  var out: List<{result}> = []\n  \
             let words: List<U32> = {}\n  for a in words {{\n    out.push({apply})\n  }}\n  out\n}}\n",
            word_list(&operands)
        )
        .unwrap();
        expected.push((name.to_string(), format!("[{}]", values.join(", "))));
    }
    let ints: Vec<i64> = vec![
        0,
        1,
        -1,
        255,
        256,
        i64::from(u32::MAX),
        i64::from(u32::MAX) + 1,
        i64::MIN,
        i64::MAX,
        rng.next(),
        rng.next(),
    ];
    let from_int: [(&str, &str, &str, Vec<String>); 3] = [
        (
            "int_to_u32_all",
            "Int",
            "match n.to_u32() {\n      Some(x) => x.to_int()\n      None => -1\n    }",
            ints.iter()
                .map(|n| u32::try_from(*n).map_or(-1, i64::from).to_string())
                .collect(),
        ),
        (
            "int_wrap_u32_all",
            "U32",
            "n.wrap_u32()",
            ints.iter().map(|n| (*n as u32).to_string()).collect(),
        ),
        (
            "int_wrap_byte_all",
            "Byte",
            "n.wrap_byte()",
            ints.iter().map(|n| (*n as u8).to_string()).collect(),
        ),
    ];
    for (name, result, apply, values) in from_int {
        writeln!(
            source,
            "fn {name}() -> List<{result}> {{\n  var out: List<{result}> = []\n  \
             for n in {} {{\n    out.push({apply})\n  }}\n  out\n}}\n",
            list(&ints)
        )
        .unwrap();
        expected.push((name.to_string(), format!("[{}]", values.join(", "))));
    }
    let bytes: [u8; 5] = [0, 1, 127, 128, 255];
    writeln!(
        source,
        "fn byte_to_u32_all() -> List<U32> {{\n  var out: List<U32> = []\n  \
         let bytes: Bytes = [0, 1, 127, 128, 255]\n  for b in bytes {{\n    out.push(b.to_u32())\n  }}\n  out\n}}\n"
    )
    .unwrap();
    expected.push((
        "byte_to_u32_all".to_string(),
        shown_words(&bytes.map(u32::from)),
    ));
    // One SHA-1 round's shape, levels mixed without parentheses.
    let r = random(&mut rng, 4);
    let (a, b, c, d) = (r[0], r[1], r[2], r[3]);
    writeln!(
        source,
        "fn mixed() -> List<U32> {{\n  let w: List<U32> = [{a}, {b}, {c}, {d}]\n  \
         let a = w[0]\n  let b = w[1]\n  let c = w[2]\n  let d = w[3]\n  let k: U32 = 0x5A827999\n  \
         [b & c | ~b & d, a.rotate_left(5) + (b ^ c ^ d) + k + w[3], a >> 3 ^ b << 7 | c, a * 3 - b + 1]\n}}\n"
    )
    .unwrap();
    let mixed = [
        (b & c) | (!b & d),
        a.rotate_left(5)
            .wrapping_add(b ^ c ^ d)
            .wrapping_add(0x5A82_7999)
            .wrapping_add(d),
        ((a >> 3) ^ (b << 7)) | c,
        a.wrapping_mul(3).wrapping_sub(b).wrapping_add(1),
    ];
    expected.push(("mixed".to_string(), shown_words(&mixed)));
    source.push_str(
        "fn show(text: Text) -> Result<Unit, IoError> requires [stdout.write] {\n  \
         var bytes = text.to_bytes()\n  bytes.push(10)\n  return Stdout.write_all(bytes)\n}\n\n\
         type Printer {\n  executable: Text\n}\n\n\
         fn Printer.main(self: Printer) -> Result<Unit, IoError> {\n",
    );
    for (name, _) in &expected {
        writeln!(source, "  show({name}().debug())?").unwrap();
    }
    source.push_str(
        "  Ok(Unit)\n}\n\nsystem Words {\n  component wordprint: Printer { executable = \"wordprint\" }\n}\n",
    );
    (source, expected)
}

/// The generated program's fns through the evaluator and both targets'
/// `print` executable, each against `expected`.
fn agree(name: &str, exe: &str, seed: u64, source: &str, expected: &[(String, String)]) {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(name);
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("differential.ignite");
    std::fs::write(&file, source).unwrap();

    let loaded = ignite::load(&file, None).unwrap_or_else(|e| panic!("seed {seed}: {e}"));
    let modules = loaded.modules();
    let mut evaluator = Evaluator::new(&modules, Fuel::default());
    let module = loaded.types().module.clone();
    for (name, want) in expected {
        let got = evaluator
            .call(&QualName::new(module.clone(), name.clone()), Vec::new())
            .unwrap_or_else(|e| panic!("seed {seed}, evaluator {name}: {e:?}"))
            .debug_text();
        assert_eq!(&got, want, "seed {seed}, evaluator {name}");
    }

    std::thread::scope(|scope| {
        let handles: Vec<_> = [Target::Rust, Target::Llvm]
            .into_iter()
            .map(|target| {
                let (file, dir) = (&file, &dir);
                scope.spawn(move || {
                    let out = dir.join(format!("out-{target:?}").to_lowercase());
                    let exes = build(file, target, out, false, None);
                    let found = exes
                        .iter()
                        .find(|p| p.file_stem().and_then(|s| s.to_str()) == Some(exe))
                        .unwrap_or_else(|| panic!("no {exe} in {exes:?}"))
                        .clone();
                    (target, run_lines(&found))
                })
            })
            .collect();
        for handle in handles {
            let (target, lines) = handle.join().expect("target thread");
            assert_eq!(lines.len(), expected.len(), "seed {seed}, {target:?}");
            for ((name, want), got) in expected.iter().zip(&lines) {
                assert_eq!(got, want, "seed {seed}, {target:?} {name}");
            }
        }
    });
}

