/// The wall time of one run of `exe`, and its output.
fn timed(exe: &Path) -> (Duration, String) {
    let start = Instant::now();
    let output = Command::new(exe).output().expect("run");
    let elapsed = start.elapsed();
    assert!(output.status.success(), "{}", exe.display());
    (
        elapsed,
        String::from_utf8_lossy(&output.stdout).into_owned(),
    )
}

fn median(mut times: Vec<Duration>) -> Duration {
    times.sort();
    times[times.len() / 2]
}

/// Runs of each executable in [`codecs_within_3x_of_hand_written_rust`],
/// interleaved so that a change of the host's load falls on all three.
const RUNS: usize = 9;

/// 29.5: the codecs' executable (SHA-1 and base64 of 1 MiB, 16 rounds)
/// built `--release` on each target, the LLVM one linking a release
/// runtime as an installed driver does, against `fixtures/bitwise/codecs.rs`
/// built with `rustc -O`; each median within 3x. Ignored: it builds a
/// release runtime and times programs; `cargo test -p ignite --test main
/// bitwise::codecs -- --ignored --nocapture` prints the record.
#[test]
#[ignore]
fn codecs_within_3x_of_hand_written_rust() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("bitwise-bench");
    std::fs::create_dir_all(&dir).unwrap();
    let rt = dir.join("rt");
    let status = Command::new(env!("CARGO"))
        .args([
            "build",
            "-q",
            "-p",
            "ignite-rt",
            "--release",
            "--target-dir",
        ])
        .arg(&rt)
        .status()
        .expect("run cargo");
    assert!(status.success(), "release runtime");
    let runtime = rt.join("release/libignite_rt.a");
    let reference = dir.join("codecs-rs");
    let status = Command::new("rustc")
        .args(["-O", "--edition", "2024", "-o"])
        .arg(&reference)
        .arg(Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/bitwise/codecs.rs"))
        .status()
        .expect("run rustc");
    assert!(status.success(), "rustc");
    let mut exes = vec![("hand-written Rust", reference)];
    for (name, target) in [("Rust target", Target::Rust), ("LLVM target", Target::Llvm)] {
        let out = dir.join(format!("out-{target:?}").to_lowercase());
        let built = build(&codecs(), target, out, true, Some(runtime.clone()));
        let exe = built
            .iter()
            .find(|p| p.file_stem().and_then(|s| s.to_str()) == Some("codecs"))
            .unwrap_or_else(|| panic!("no codecs in {built:?}"))
            .clone();
        exes.push((name, exe));
    }
    let mut times = vec![Vec::new(); exes.len()];
    let mut printed = vec![String::new(); exes.len()];
    for _ in 0..RUNS {
        for (index, (_, exe)) in exes.iter().enumerate() {
            let (time, out) = timed(exe);
            times[index].push(time);
            printed[index] = out;
        }
    }
    let medians: Vec<Duration> = times.into_iter().map(median).collect();
    println!("{}: {:?}", exes[0].0, medians[0]);
    for index in 1..exes.len() {
        let name = exes[index].0;
        assert_eq!(
            printed[index], printed[0],
            "{name} prints what the reference prints"
        );
        let ratio = medians[index].as_secs_f64() / medians[0].as_secs_f64();
        println!("{name}: {:?}, ratio {ratio:.2}", medians[index]);
        assert!(
            ratio <= 3.0,
            "{name}: {ratio:.2} times the hand-written Rust"
        );
    }
}
